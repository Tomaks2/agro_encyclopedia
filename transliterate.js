function transliterate(text) {
    let res = '';
    for (const char of text) {
        if (uaToLatMap[char] !== undefined) res += uaToLatMap[char];
        else if (/[a-zA-Z0-9_\-\.]/.test(char)) res += char;
        else res += '-';
    }
    return res.replace(/-+/g, '-').replace(/^-|-$/g, '').toLowerCase();
}

